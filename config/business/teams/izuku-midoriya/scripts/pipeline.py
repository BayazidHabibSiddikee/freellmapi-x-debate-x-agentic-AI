# ── Step 4: Generate Images ─────────────────────────────────────────────────

def step_4_generate_images(iteration: int, hook_data: dict) -> Path:
    """Generate AI scene images from story descriptions — contextual to the story, not stock footage."""
    log(f"Iter {iteration}: Generating AI scene images")
    img_dir = IMAGES_DIR / f"iter_{iteration:02d}"
    img_dir.mkdir(exist_ok=True)

    scene_images = sorted(img_dir.glob("scene_*.jpg")) + sorted(img_dir.glob("scene_*.png"))
    if len(scene_images) >= 5:
        log(f"  AI images exist: {len(scene_images)} files")
        return img_dir

    # Generate scene descriptions from the story chapter
    chapter_file = STORIES_DIR / f"chapter_{iteration:02d}.md"
    chapter_text = chapter_file.read_text() if chapter_file.exists() else ""

    paragraphs = [p.strip() for p in chapter_text.split("\n\n") if p.strip() and not p.strip().startswith("#") and not p.strip().startswith("[")]
    scene_prompts = []
    for p in paragraphs[:5]:
        prompt = f"cinematic anime style, {p[:200]}, dramatic lighting, epic composition, 4k quality"
        scene_prompts.append(prompt)

    if not scene_prompts:
        scene_prompts = [
            f"cinematic anime, {hook_data.get('title', 'war survivor')}, epic dramatic scene",
            "military medic saving wounded soldier, anime style, dramatic lighting",
            "young hero in battlefield ruins, anime, cinematic composition",
            "soldiers running through smoke and fire, anime style, action scene",
            "hero standing victorious on battlefield, anime, epic pose",
        ]

    import urllib.request
    import urllib.parse

    for j, prompt in enumerate(scene_prompts[:5]):
        scene_img = img_dir / f"scene_{j+1:02d}.jpg"
        if scene_img.exists():
            continue

        encoded = urllib.parse.quote(prompt)
        url = f"https://image.pollinations.ai/prompt/{encoded}?width=1080&height=1920&seed={j + iteration * 10}&nologo=true"
        log(f"  Generating scene {j+1}: {prompt[:60]}...")

        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=60) as resp:
                scene_img.write_bytes(resp.read())
            if scene_img.exists() and scene_img.stat().st_size > 5000:
                log(f"  Scene {j+1} OK: {scene_img.stat().st_size // 1024}KB")
            else:
                log(f"  Scene {j+1} too small, retrying...")
                scene_img.unlink(missing_ok=True)
        except Exception as e:
            log(f"  Scene {j+1} failed: {e}")

    scene_images = sorted(img_dir.glob("scene_*.jpg")) + sorted(img_dir.glob("scene_*.png"))
    log(f"  Generated {len(scene_images)} AI scene images")
    return img_dir


# ── Step 5: Generate Voices ─────────────────────────────────────────────────

def step_5_generate_voices(iteration: int, story_file: Path) -> Path:
    """Generate voiceover using Piper TTS (local neural voice)."""
    log(f"Iter {iteration}: Generating voiceover")
    voice_file = VOICES_DIR / f"narration_{iteration:02d}.wav"

    if voice_file.exists():
        log(f"  Voice exists: {voice_file.name}")
        return voice_file

    story_text = story_file.read_text() if story_file.exists() else ""
    # Strip markdown headers and metadata
    clean_text = ""
    for line in story_text.split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("[") or line.startswith("---"):
            continue
        clean_text += line + " "

    if not clean_text.strip():
        log("  No text to synthesize")
        voice_file.write_text(f"[Empty text for chapter {iteration}]")
        return voice_file

    # Piper TTS — local neural voice, much better than edge-tts
    piper_model = Path("/home/sword/Documents/piper-voices/en_US-ryan-medium.onnx")
    if not piper_model.exists():
        log("  Piper model not found, falling back to edge-tts")
        piper_model = None

    if piper_model:
        try:
            import subprocess
            text_file = VOICES_DIR / f"text_{iteration:02d}.txt"
            text_file.write_text(clean_text[:3000])

            result = subprocess.run(
                ["piper", "-m", str(piper_model), "-f", str(voice_file)],
                input=clean_text[:3000],
                capture_output=True, text=True, timeout=120,
            )
            if voice_file.exists():
                log(f"  Voice generated (Piper): {voice_file.name}")
            else:
                log(f"  Piper failed: {result.stderr[:200]}")
                voice_file.write_text(f"[Piper failed for chapter {iteration}]")
        except Exception as e:
            log(f"  Piper error: {e}")
            voice_file.write_text(f"[Piper error for chapter {iteration}]")
    else:
        # Fallback to edge-tts
        try:
            import asyncio
            import edge_tts

            async def _tts():
                comm = edge_tts.Communicate(clean_text[:1500], voice="en-US-GuyNeural", rate="-10%")
                await comm.save(str(voice_file))

            asyncio.run(_tts())
            log(f"  Voice generated (edge-tts fallback): {voice_file.name}")
        except Exception as e:
            log(f"  edge-tts failed ({e})")
            voice_file.write_text(f"[TTS failed for chapter {iteration}]")

    return voice_file


# ── Step 6: Assemble Video ──────────────────────────────────────────────────

def step_6_assemble_video(iteration: int, img_dir: Path, voice_file: Path, hook_data: dict) -> Path:
    """Assemble video using DramaClaw: scene images + Piper audio + Ken Burns + title/end cards."""
    log(f"Iter {iteration}: Assembling video (DramaClaw)")
    output_file = OUTPUT_DIR / f"izuku_chapter_{iteration:02d}.mp4"

    if output_file.exists() and output_file.stat().st_size > 100000:
        log(f"  Video exists: {output_file.name}")
        return output_file

    import subprocess

    # Step A: Get AI-generated scene images
    scene_images = sorted(img_dir.glob("scene_*.jpg")) + sorted(img_dir.glob("scene_*.png"))
    if not scene_images:
        log("  No scene images available — run step_4 first")
        output_file.write_text(f"[No images for chapter {iteration}]")
        return output_file

    # Step B: Split Piper audio into scene segments
    story_file = STORIES_DIR / f"chapter_{iteration:02d}.md"
    story_text = story_file.read_text() if story_file.exists() else ""
    paragraphs = [p.strip() for p in story_text.split("\n\n") if p.strip() and not p.strip().startswith("#") and not p.strip().startswith("[")]
    if not paragraphs:
        paragraphs = [story_text[:500]]

    # Get audio duration
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(voice_file)],
        capture_output=True, text=True,
    )
    total_duration = float(probe.stdout.strip() or "60")
    segment_duration = total_duration / max(len(paragraphs), len(scene_images))

    # Split audio into segments
    audio_segments = []
    for j in range(len(scene_images)):
        seg_file = img_dir / f"audio_{j+1:02d}.wav"
        start = j * segment_duration
        subprocess.run(
            ["ffmpeg", "-y", "-i", str(voice_file), "-ss", str(start), "-t", str(segment_duration), str(seg_file)],
            capture_output=True, timeout=30,
        )
        audio_segments.append(seg_file)

    # Step C: Use DramaClaw's Ken Burns + scene composition
    sys.path.insert(0, "/home/sword/freellmapi-x-debate-x-agentic-AI/config/business/teams/izuku-midoriya/scripts")
    from dramaclaw_video import assemble_episode, KenBurnsEffect

    scenes = []
    for j in range(len(scene_images)):
        audio_file = audio_segments[j] if j < len(audio_segments) else audio_segments[0]
        if audio_file.exists():
            scenes.append({
                "image_path": str(scene_images[j]),
                "audio_path": str(audio_file),
                "duration_seconds": segment_duration,
                "narration_text": paragraphs[j] if j < len(paragraphs) else "",
            })

    if not scenes:
        log("  No scenes to assemble")
        output_file.write_text(f"[No scenes for chapter {iteration}]")
        return output_file

    log(f"  Assembling {len(scenes)} scenes with Ken Burns effects...")
    title = hook_data.get("title", f"Chapter {iteration}")

    success = assemble_episode(
        scenes=scenes,
        output_path=str(output_file),
        title=title,
        add_title_card=True,
        add_end_card=True,
        width=1080,
        height=1920,
    )

    if success and output_file.exists() and output_file.stat().st_size > 100000:
        log(f"  Video assembled: {output_file.name} ({output_file.stat().st_size // 1024}KB)")
    else:
        log("  DramaClaw assembly failed, falling back to simple concat")
        # Fallback: simple concat of Pexels clips + Piper audio
        clip_files = sorted(img_dir.glob("clip_*.mp4"))
        if clip_files:
            concat_file = OUTPUT_DIR / f"concat_{iteration:02d}.txt"
            concat_file.write_text("\n".join(f"file '{f}'" for f in clip_files))
            subprocess.run(
                ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(concat_file),
                 "-c", "copy", str(output_file)],
                capture_output=True, timeout=60,
            )

    return output_file


