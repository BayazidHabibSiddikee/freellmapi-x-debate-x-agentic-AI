# ── Main Pipeline ────────────────────────────────────────────────────────────

def run_pipeline():
    ensure_dirs()
    log("=" * 60)
    log("IZUKU MIDORIYA CONTENT PIPELINE — 10 ITERATIONS")
    log(f"Niche: {NICHE}")
    log("=" * 60)

    for i in range(1, ITERATIONS + 1):
        log(f"\n{'─' * 40}")
        log(f"ITERATION {i}/{ITERATIONS}")
        log(f"{'─' * 40}")

        ok = step_1_researcher_ingest(i)
        if not ok:
            log("  SKIP: no books. Add war story files to books/ first.")
            continue

        story = step_2_writer_draft(i)
        hook_file = step_3_marketing_hook(i, story)
        hook_data = json.loads(hook_file.read_text())
        imgs = step_4_generate_images(i, hook_data)
        voice = step_5_generate_voices(i, story)
        video = step_6_assemble_video(i, imgs, voice, hook_data)
        step_7_post_social(i, video, hook_data)
        step_8_notify(i, video, hook_data)

        log(f"Iteration {i} COMPLETE ✓")

    log("\n" + "=" * 60)
    log("PIPELINE FINISHED — 10 iterations complete")
    log("=" * 60)

    # Final summary
    summary_file = OUTPUT_DIR / "summary.json"
    if summary_file.exists():
        summaries = json.loads(summary_file.read_text())
        log(f"\nTotal videos: {len(summaries)}")
        for s in summaries:
            log(f"  Ch {s['iteration']}: {s['title']}")


if __name__ == "__main__":
    run_pipeline()
