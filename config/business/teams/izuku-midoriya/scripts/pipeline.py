# ── Step 1: Researcher Ingest ────────────────────────────────────────────────

def step_1_researcher_ingest(iteration: int) -> bool:
    """Researcher scans books/ dir, ingests new files into rag/."""
    log(f"Iter {iteration}: Researcher ingesting books")
    books = list(BOOKS_DIR.glob("*"))
    if not books:
        log("  No books found — add war story files to books/")
        return False

    ingested = 0
    for b in books:
        if b.name.startswith("."):
            continue
        dest = RAG_DIR / b.name
        if not dest.exists():
            shutil.copy2(b, dest)
            ingested += 1
            log(f"  Ingested: {b.name}")

    log(f"  {len(books)} source files, {ingested} new")
    return True


# ── Step 2: Writer Draft ────────────────────────────────────────────────────

def step_2_writer_draft(iteration: int) -> Path:
    """Writer drafts a story chapter from RAG context."""
    log(f"Iter {iteration}: Writer drafting chapter")
    story_file = STORIES_DIR / f"chapter_{iteration:02d}.md"

    # Read any existing RAG context
    rag_context = ""
    for f in RAG_DIR.glob("*"):
        if f.is_file() and f.suffix in [".txt", ".md"]:
            try:
                rag_context += f.read_text()[:2000] + "\n"
            except Exception:
                pass

    chapter_prompt = f"""You are writing Chapter {iteration} of the Izuku Midoriya war survival story.

Setting: Post-apocalyptic battlefield. Izuku is the last surviving medic in a ruined city.
Style: Visceral, cinematic, 300-400 words. First-person from Izuku's perspective.

{f"Source material context:{chr(10)}{rag_context[:1500]}" if rag_context else ""}

Write Chapter {iteration}. End with a cliffhanger leading into Chapter {iteration+1}.
Output ONLY the story text, no metadata."""

    story_file.write_text(
        f"# Chapter {iteration} — The Last Medic\n\n"
        f"[Generated: {datetime.now().isoformat()}]\n\n"
        f"---\n\n"
        f"[To be generated by Writer agent using the following prompt:\n{chapter_prompt}]\n"
    )
    log(f"  Drafted: {story_file.name}")
    return story_file


